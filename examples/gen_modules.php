<?php
// Generates `crates/p8-stubs/src/modules.rs`: the extension (module) PHP
// names for each builtin function and class, as reflection reports it
// (ReflectionFunction::getExtensionName(), "<internal:Core>").
//
//     docker run --rm -i p8-php-apps:50ebaed2745d php < examples/gen_modules.php > crates/p8-stubs/src/modules.rs
//
// The image has the extensions p8 ships (and more; a name p8 has no
// builtin for is simply never looked up).

$functions = [];
foreach (get_extension_funcs('Core') ?: [] as $f) {
    $functions[strtolower($f)] = 'Core';
}
foreach (get_loaded_extensions() as $ext) {
    foreach (get_extension_funcs($ext) ?: [] as $f) {
        $functions[strtolower($f)] = (new ReflectionFunction($f))->getExtensionName();
    }
}
$classes = [];
foreach (array_merge(get_declared_classes(), get_declared_interfaces(), get_declared_traits()) as $c) {
    $r = new ReflectionClass($c);
    if ($r->isInternal()) {
        $classes[strtolower($c)] = $r->getExtensionName();
    }
}
ksort($functions, SORT_STRING);
ksort($classes, SORT_STRING);

echo "//! Generated by `examples/gen_modules.php` from PHP 8.4.27; do not edit.\n";
echo "//! The extension each builtin function and class belongs to, by\n";
echo "//! lowercase name, sorted (binary search).\n\n";
echo "pub static FUNCTION_MODULES: &[(&str, &str)] = &[\n";
foreach ($functions as $f => $m) {
    printf("    (\"%s\", \"%s\"),\n", addcslashes($f, '\\"'), $m);
}
echo "];\n\npub static CLASS_MODULES: &[(&str, &str)] = &[\n";
foreach ($classes as $c => $m) {
    printf("    (\"%s\", \"%s\"),\n", addcslashes($c, '\\"'), $m);
}
echo "];\n";
