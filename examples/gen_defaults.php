<?php
// Generates `crates/p8-ext-standard/src/defaults.rs`: every constant and every ini
// directive (with its built-in default) that PHP 8.6 defines in the
// extensions this runtime ships.
//
//     docker run --rm -i php:8.6-cli php < examples/gen_defaults.php > crates/p8-ext-standard/src/defaults.rs
//
// (The official 8.6 images have no mbstring: add it first, as
// tests/php-src/php-src.Dockerfile does, or use p8-lanes' verify/php.Dockerfile.)
//
// Values come from a real PHP with no php.ini (on Linux, like the reference
// test run), so they match exactly. Constants that describe the build or the
// host (paths, the OS) are left out: the runtime defines those itself.

const EXTENSIONS = ['Core', 'standard', 'date', 'pcre', 'json', 'mbstring', 'hash', 'zlib', 'SPL', 'random', 'ctype', 'tokenizer', 'filter'];

const HOST = [
    'PHP_BINARY', 'PHP_BINDIR', 'PHP_LIBDIR', 'PHP_DATADIR', 'PHP_SYSCONFDIR',
    'PHP_LOCALSTATEDIR', 'PHP_CONFIG_FILE_PATH', 'PHP_CONFIG_FILE_SCAN_DIR',
    'PHP_SHLIB_SUFFIX', 'PHP_EXTENSION_DIR', 'PHP_PREFIX', 'PHP_MANDIR',
    'DEFAULT_INCLUDE_PATH', 'PEAR_INSTALL_DIR', 'PEAR_EXTENSION_DIR',
    'PHP_OS', 'PHP_OS_FAMILY', 'PHP_SAPI', 'PHP_MAXPATHLEN', 'PHP_FD_SETSIZE',
    'PHP_VERSION', 'PHP_VERSION_ID', 'PHP_EXTRA_VERSION', 'PHP_RELEASE_VERSION',
    'PHP_MAJOR_VERSION', 'PHP_MINOR_VERSION', 'PHP_ZTS', 'PHP_DEBUG',
    'ZEND_THREAD_SAFE', 'ZEND_DEBUG_BUILD', 'PHP_EOL', 'DIRECTORY_SEPARATOR',
    'PATH_SEPARATOR', 'PHP_BUILD_DATE', 'PHP_BUILD_PROVIDER',
];

function rust_bytes(string $s): string
{
    $out = '';
    foreach (str_split($s) as $c) {
        $o = ord($c);
        $out .= ($o >= 0x20 && $o < 0x7f && $c !== '"' && $c !== '\\') ? $c : sprintf('\\x%02x', $o);
    }
    return 'b"' . $out . '"';
}

echo "//! Generated by `examples/gen_defaults.php` from PHP ", PHP_VERSION, "; do not edit.\n";
echo "//! The constants and ini directives of the extensions this runtime ships,\n";
echo "//! with real PHP's values.\n\n";
echo "pub enum ConstValue {\n    Int(i64),\n    Float(u64),\n    Str(&'static [u8]),\n    Bool(bool),\n    Null,\n}\n\n";
echo "/// (extension, name, value, deprecated).\n";
echo "pub static CONSTANTS: &[(&str, &[u8], ConstValue, bool)] = &[\n";
$all = get_defined_constants(true);
foreach (EXTENSIONS as $ext) {
    foreach ($all[$ext] ?? [] as $name => $value) {
        if (in_array($name, HOST, true)) {
            continue;
        }
        $v = match (true) {
            is_int($value) => "ConstValue::Int($value)",
            is_float($value) => sprintf('ConstValue::Float(0x%s)', bin2hex(strrev(pack('d', $value)))),
            is_string($value) => 'ConstValue::Str(' . rust_bytes($value) . ')',
            is_bool($value) => 'ConstValue::Bool(' . ($value ? 'true' : 'false') . ')',
            is_null($value) => 'ConstValue::Null',
            default => null,
        };
        if ($v !== null) {
            $deprecated = (new ReflectionConstant($name))->isDeprecated() ? 'true' : 'false';
            printf("    (%s, %s, %s, %s),\n", '"' . strtolower($ext) . '"', rust_bytes($name), $v, $deprecated);
        }
    }
}
echo "];\n";

// Directives no extension claims belong to the engine ("core").
$all_ini = ini_get_all(null, false);
$owner = array_fill_keys(array_keys($all_ini), 'core');
foreach (get_loaded_extensions() as $ext) {
    foreach (array_keys(@ini_get_all($ext, false) ?: []) as $name) {
        $owner[$name] = strtolower($ext);
    }
}
echo "\n/// (extension, directive, built-in default; None where PHP has no value).\n";
echo "pub static INI_DEFAULTS: &[(&str, &str, Option<&[u8]>)] = &[\n";
foreach ($all_ini as $name => $value) {
    $ext = $owner[$name];
    if ($ext !== 'core' && !in_array($ext, array_map('strtolower', EXTENSIONS), true)) {
        continue;
    }
    printf("    (\"%s\", \"%s\", %s),\n", $ext, $name, $value === null ? 'None' : 'Some(' . rust_bytes($value) . ')');
}
echo "];\n";

// ini_get_all() reports who may change each directive (PHP_INI_USER 1,
// PHP_INI_PERDIR 2, PHP_INI_SYSTEM 4, PHP_INI_ALL 7).
echo "\n/// Each directive's access level, as ini_get_all() reports it.\n";
echo "pub static INI_ACCESS: &[(&str, u8)] = &[\n";
foreach (ini_get_all(null, true) as $name => $info) {
    $ext = $owner[$name];
    if ($ext !== 'core' && !in_array($ext, array_map('strtolower', EXTENSIONS), true)) {
        continue;
    }
    printf("    (\"%s\", %d),\n", $name, $info['access']);
}
echo "];\n";

// opcache_get_configuration() reports each directive with a type.
echo "\n/// The type opcache_get_configuration() gives each directive: b(ool), i(nt), f(loat), s(tring).\n";
echo "pub static OPCACHE_DIRECTIVE_TYPES: &[(&str, char)] = &[\n";
foreach (opcache_get_configuration()['directives'] as $name => $value) {
    printf("    (\"%s\", '%s'),\n", $name, match (true) { is_bool($value) => 'b', is_int($value) => 'i', is_float($value) => 'f', default => 's' });
}
echo "];\n";
