//! Generates `crates/p8-stubs/src/table.rs`, the signature of every PHP
//! function and method of a built-in class declared in php-src's
//! `*.stub.php` files: parameter names, types, by-reference and variadic
//! flags, defaults, return types.
//!
//!     cargo run --example gen_signatures -- ../php-src > crates/p8-stubs/src/table.rs
//!
//! The stubs are the source PHP itself generates its arginfo from, so names
//! and types match exactly.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

/// Type bits, in the order zend_type_to_string prints them.
const TYPE_BITS: &[(&str, u32)] = &[
    ("mixed", 1 << 0),
    ("static", 1 << 1),
    ("callable", 1 << 2),
    ("object", 1 << 3),
    ("array", 1 << 4),
    ("string", 1 << 5),
    ("int", 1 << 6),
    ("float", 1 << 7),
    ("bool", 1 << 8),
    ("false", 1 << 9),
    ("true", 1 << 10),
    ("void", 1 << 11),
    ("never", 1 << 12),
    ("null", 1 << 13),
];

struct Param {
    name: String,
    mask: u32,
    classes: Vec<String>,
    by_ref: bool,
    variadic: bool,
    default: Option<String>,
}

struct Func {
    /// `strlen`, or `ArrayAccess::offsetSet` for a method.
    name: String,
    params: Vec<Param>,
    ret_mask: u32,
    ret_classes: Vec<String>,
    /// `@tentative-return-type`: overriding without it is only deprecated.
    tentative: bool,
    returns_ref: bool,
    /// Method modifiers: 1 final, 2 static, 4 abstract, 8 private, 16 protected.
    flags: u8,
    /// Index of its #[\Deprecated] attribute's (since, message).
    deprecated: Option<usize>,
}

fn main() {
    let root = std::env::args()
        .nth(1)
        .expect("usage: gen_signatures <php-src directory>");
    let mut stubs = Vec::new();
    collect_stubs(Path::new(&root), &mut stubs);
    stubs.sort();

    let mut funcs: Vec<Func> = Vec::new();
    let mut deprecations: Vec<(Option<String>, Option<String>)> = Vec::new();
    for path in &stubs {
        // The zend_test extension declares test-only functions.
        if path.components().any(|c| c.as_os_str() == "zend_test") {
            continue;
        }
        let src = std::fs::read_to_string(path).expect("read stub");
        let src = mark_deprecated(&src, &mut deprecations);
        parse_stub(&strip(&mark_tentative(&src)), &mut funcs);
    }
    funcs.sort_by_key(|f| f.name.to_ascii_lowercase());
    funcs.dedup_by(|a, b| a.name.eq_ignore_ascii_case(&b.name));

    let mut out = String::new();
    out.push_str(
        "// @generated by examples/gen_signatures.rs from php-src 8.4's *.stub.php files.\n\
         // Do not edit by hand; regenerate instead.\n\n\
         use super::{Param, Sig};\n\n\
         /// Functions and methods (`Class::method`), sorted by lowercase name.\n\
         #[rustfmt::skip]\n\
         pub static SIGNATURES: &[Sig] = &[\n",
    );
    for f in &funcs {
        let _ = write!(out, "    Sig {{ name: {:?}, params: &[", f.name);
        for (i, p) in f.params.iter().enumerate() {
            if i > 0 {
                out.push_str(", ");
            }
            let _ = write!(
                out,
                "Param {{ name: {:?}, mask: {:#x}, classes: &{:?}, by_ref: {}, variadic: {}, default: {:?} }}",
                p.name, p.mask, p.classes, p.by_ref, p.variadic, p.default
            );
        }
        let _ = writeln!(
            out,
            "], ret_mask: {:#x}, ret_classes: &{:?}, tentative: {}, returns_ref: {}, flags: {} }},",
            f.ret_mask, f.ret_classes, f.tentative, f.returns_ref, f.flags
        );
    }
    out.push_str("];\n");
    out.push_str(
        "\n/// Functions and methods declared #[\\Deprecated]: (name, since, message),\n\
         /// sorted by lowercase name.\n\
         #[rustfmt::skip]\n\
         pub static DEPRECATED: &[(&str, Option<&str>, Option<&str>)] = &[\n",
    );
    for f in funcs.iter().filter(|f| f.deprecated.is_some()) {
        let (since, message) = &deprecations[f.deprecated.unwrap_or_default()];
        let _ = writeln!(out, "    ({:?}, {:?}, {:?}),", f.name, since, message);
    }
    out.push_str("];\n");
    print!("{out}");
}

fn collect_stubs(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            if path
                .file_name()
                .is_some_and(|n| n == ".git" || n == "tests")
            {
                continue;
            }
            collect_stubs(&path, out);
        } else if path.to_string_lossy().ends_with(".stub.php") {
            out.push(path);
        }
    }
}

/// Remove comments and attributes, keeping strings intact.
fn strip(src: &str) -> String {
    let b = src.as_bytes();
    let mut out = String::with_capacity(src.len());
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'/' if b.get(i + 1) == Some(&b'*') => {
                i = src[i + 2..].find("*/").map_or(b.len(), |p| i + 2 + p + 2);
            }
            b'/' if b.get(i + 1) == Some(&b'/') => {
                i = src[i..].find('\n').map_or(b.len(), |p| i + p);
            }
            b'#' if b.get(i + 1) == Some(&b'[') => {
                let mut depth = 0;
                while i < b.len() {
                    match b[i] {
                        b'[' => depth += 1,
                        b']' => {
                            depth -= 1;
                            if depth == 0 {
                                i += 1;
                                break;
                            }
                        }
                        _ => {}
                    }
                    i += 1;
                }
            }
            b'#' => {
                i = src[i..].find('\n').map_or(b.len(), |p| i + p);
            }
            q @ (b'\'' | b'"') => {
                let start = i;
                i += 1;
                while i < b.len() && b[i] != q {
                    if b[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
                i += 1;
                out.push_str(&src[start..i.min(b.len())]);
            }
            _ => {
                let ch = src[i..].chars().next().unwrap();
                out.push(ch);
                i += ch.len_utf8();
            }
        }
    }
    out
}

/// Keep `@tentative-return-type` through comment stripping: the doc
/// comment becomes a marker the parser attaches to the next function.
/// Replace each `#[\\Deprecated(since: ..., message: ...)]` with a
/// `__DEPRECATED_<n>__` marker naming its entry in `found`, so the parser
/// (which drops attributes) can attach it to the next declaration.
fn mark_deprecated(src: &str, found: &mut Vec<(Option<String>, Option<String>)>) -> String {
    let mut out = String::with_capacity(src.len());
    let mut rest = src;
    while let Some(start) = rest.find("#[\\Deprecated") {
        out.push_str(&rest[..start]);
        let attr = &rest[start..];
        let end = attr.find(")]").map_or(attr.find(']').map_or(attr.len(), |e| e + 1), |e| e + 2);
        let args = &attr[..end];
        let arg = |key: &str| -> Option<String> {
            let at = args.find(&format!("{key}:"))? + key.len() + 1;
            let value = args[at..].trim_start();
            let quote = value.chars().next()?;
            let mut text = String::new();
            let mut chars = value[1..].chars();
            while let Some(c) = chars.next() {
                match c {
                    '\\' => text.extend(chars.next()),
                    c if c == quote => break,
                    c => text.push(c),
                }
            }
            Some(text)
        };
        found.push((arg("since"), arg("message")));
        out.push_str(&format!(" __DEPRECATED_{}__ ", found.len() - 1));
        rest = &attr[end..];
    }
    out.push_str(rest);
    out
}

fn mark_tentative(src: &str) -> String {
    let mut out = String::with_capacity(src.len());
    let mut rest = src;
    while let Some(start) = rest.find("/**") {
        out.push_str(&rest[..start]);
        let end = rest[start..].find("*/").map_or(rest.len(), |e| start + e + 2);
        let comment = &rest[start..end];
        if comment.contains("@tentative-return-type") {
            out.push_str(" __TENTATIVE__ ");
        } else {
            out.push_str(comment);
        }
        rest = &rest[end..];
    }
    out.push_str(rest);
    out
}

fn parse_stub(src: &str, funcs: &mut Vec<Func>) {
    let b = src.as_bytes();
    let mut depth = 0usize;
    // Brace depths that are `namespace X {` blocks: functions directly
    // inside them are top level.
    let mut ns_blocks: Vec<usize> = Vec::new();
    let mut namespace = String::new();
    // A class-like declaration waiting for its `{`, and the one whose body
    // we are in (name, brace depth of its body).
    let mut pending_class: Option<String> = None;
    let mut class: Option<(String, usize)> = None;
    let mut tentative = false;
    let mut deprecated: Option<usize> = None;
    let mut modifiers: u8 = 0;
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        if c == b'\'' || c == b'"' {
            i += 1;
            while i < b.len() && b[i] != c {
                if b[i] == b'\\' {
                    i += 1;
                }
                i += 1;
            }
            i += 1;
            continue;
        }
        if c == b';' {
            modifiers = 0;
            deprecated = None;
        }
        if c == b'{' {
            modifiers = 0;
            deprecated = None;
            depth += 1;
            if let Some(name) = pending_class.take() {
                class = Some((name, depth));
            }
            i += 1;
            continue;
        }
        if c == b'}' {
            modifiers = 0;
            if class.as_ref().is_some_and(|(_, d)| *d == depth) {
                class = None;
            }
            if ns_blocks.last() == Some(&depth) {
                ns_blocks.pop();
                namespace.clear();
            }
            depth = depth.saturating_sub(1);
            i += 1;
            continue;
        }
        let at_word = i == 0 || !(b[i - 1].is_ascii_alphanumeric() || b[i - 1] == b'_');
        if !at_word {
            i += 1;
            continue;
        }
        let word_end = src[i..]
            .find(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_'))
            .map_or(src.len(), |e| i + e);
        let word = &src[i..word_end];
        match word {
            "namespace" => {
                let rest = &src[word_end..];
                let end = rest.find([';', '{']).unwrap_or(rest.len());
                namespace = rest[..end].trim().to_string();
                if rest.as_bytes().get(end) == Some(&b'{') {
                    depth += 1;
                    ns_blocks.push(depth);
                    i = word_end + end + 1;
                } else {
                    i = word_end + end;
                }
                continue;
            }
            "class" | "interface" | "trait" | "enum" if class.is_none() && depth == ns_blocks.len() => {
                let rest = src[word_end..].trim_start();
                let name_len = rest
                    .find(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_'))
                    .unwrap_or(rest.len());
                let name = &rest[..name_len];
                if !name.is_empty() {
                    pending_class = Some(if namespace.is_empty() {
                        name.to_string()
                    } else {
                        format!("{namespace}\\{name}")
                    });
                }
                i = word_end;
                continue;
            }
            "final" | "static" | "abstract" | "private" | "protected" => {
                modifiers |= match word {
                    "final" => 1,
                    "static" => 2,
                    "abstract" => 4,
                    "private" => 8,
                    _ => 16,
                };
                i = word_end;
                continue;
            }
            "__TENTATIVE__" => {
                tentative = true;
                i = word_end;
                continue;
            }
            w if w.starts_with("__DEPRECATED_") => {
                deprecated = w.trim_start_matches("__DEPRECATED_").trim_end_matches('_').parse().ok();
                i = word_end;
                continue;
            }
            "function" => {
                let in_class = class.as_ref().filter(|(_, d)| *d == depth).map(|(n, _)| n.clone());
                if in_class.is_none() && depth != ns_blocks.len() {
                    i = word_end;
                    continue;
                }
                let rest = &src[word_end..];
                let open = rest.find('(').expect("function without (");
                let mut name = rest[..open].trim();
                let returns_ref = name.starts_with('&');
                name = name.trim_start_matches('&').trim();
                let (params_src, after) = balanced(&rest[open..]);
                let tail = &rest[open + after..];
                let tail_end = tail.find(['{', ';']).unwrap_or(tail.len());
                let ret = tail[..tail_end].trim().strip_prefix(':').unwrap_or("").trim();
                let (ret_mask, ret_classes) = parse_type(ret);
                let full = match in_class {
                    Some(class_name) => format!("{class_name}::{name}"),
                    None if namespace.is_empty() => name.to_string(),
                    None => format!("{namespace}\\{name}"),
                };
                funcs.push(Func {
                    name: full,
                    params: split_params(params_src).iter().map(|p| parse_param(p)).collect(),
                    ret_mask,
                    ret_classes,
                    tentative: std::mem::take(&mut tentative),
                    deprecated: deprecated.take(),
                    returns_ref,
                    flags: std::mem::take(&mut modifiers),
                });
                i = word_end + open + after;
                continue;
            }
            _ => {
                i = word_end.max(i + 1);
            }
        }
    }
}

/// `(...)` at the start of `s`: the inside, and the offset after `)`.
fn balanced(s: &str) -> (&str, usize) {
    let b = s.as_bytes();
    let mut depth = 0;
    let mut i = 0;
    while i < b.len() {
        match b[i] {
            b'(' | b'[' => depth += 1,
            b')' | b']' => {
                depth -= 1;
                if depth == 0 {
                    return (&s[1..i], i + 1);
                }
            }
            q @ (b'\'' | b'"') => {
                i += 1;
                while i < b.len() && b[i] != q {
                    if b[i] == b'\\' {
                        i += 1;
                    }
                    i += 1;
                }
            }
            _ => {}
        }
        i += 1;
    }
    (&s[1..], s.len())
}

fn split_params(s: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut cur = String::new();
    let mut depth = 0;
    let mut quote: Option<char> = None;
    let mut escaped = false;
    for ch in s.chars() {
        if let Some(q) = quote {
            cur.push(ch);
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == q {
                quote = None;
            }
            continue;
        }
        match ch {
            '\'' | '"' => quote = Some(ch),
            '(' | '[' => depth += 1,
            ')' | ']' => depth -= 1,
            ',' if depth == 0 => {
                if !cur.trim().is_empty() {
                    out.push(cur.trim().to_string());
                }
                cur.clear();
                continue;
            }
            _ => {}
        }
        cur.push(ch);
    }
    if !cur.trim().is_empty() {
        out.push(cur.trim().to_string());
    }
    out
}

fn parse_param(p: &str) -> Param {
    let (decl, default) = match find_top_level_eq(p) {
        Some(pos) => (p[..pos].trim(), Some(p[pos + 1..].trim().to_string())),
        None => (p.trim(), None),
    };
    let dollar = decl.rfind('$').expect("parameter without $");
    let name = decl[dollar + 1..].trim().to_string();
    let mut head = decl[..dollar].trim().to_string();
    let variadic = head.ends_with("...");
    if variadic {
        head.truncate(head.len() - 3);
        head = head.trim().to_string();
    }
    let by_ref = head.ends_with('&');
    if by_ref {
        head.truncate(head.len() - 1);
        head = head.trim().to_string();
    }
    let (mask, classes) = parse_type(&head);
    Param {
        name,
        mask,
        classes,
        by_ref,
        variadic,
        default,
    }
}

fn find_top_level_eq(p: &str) -> Option<usize> {
    let mut quote: Option<char> = None;
    for (i, ch) in p.char_indices() {
        match quote {
            Some(q) if ch == q => quote = None,
            Some(_) => {}
            None if ch == '\'' || ch == '"' => quote = Some(ch),
            None if ch == '=' => return Some(i),
            None => {}
        }
    }
    None
}

/// A declared type as (bits, class names); untyped is (0, []).
fn parse_type(t: &str) -> (u32, Vec<String>) {
    let t = t.trim();
    if t.is_empty() {
        return (0, Vec::new());
    }
    let mut mask = 0;
    let mut classes = Vec::new();
    let (t, nullable) = match t.strip_prefix('?') {
        Some(rest) => (rest, true),
        None => (t, false),
    };
    if nullable {
        mask |= bit("null");
    }
    for part in t.split('|') {
        let part = part.trim().trim_matches(|c| c == '(' || c == ')');
        let lower = part.to_ascii_lowercase();
        if lower == "iterable" {
            mask |= bit("array");
            classes.push("Traversable".to_string());
        } else if let Some(&(_, b)) = TYPE_BITS.iter().find(|(n, _)| *n == lower) {
            mask |= b;
        } else {
            // Class (or intersection, kept as written).
            classes.push(part.trim_start_matches('\\').to_string());
        }
    }
    (mask, classes)
}

fn bit(name: &str) -> u32 {
    TYPE_BITS.iter().find(|(n, _)| *n == name).unwrap().1
}
